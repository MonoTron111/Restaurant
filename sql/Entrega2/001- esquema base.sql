-- Migracion 001: esquema base del restaurante

BEGIN;

CREATE TABLE cargo (
    id_cargo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    CONSTRAINT ck_cargo_nombre
        CHECK (nombre IN ('Mesero', 'Cocinero', 'Administrador', 'Cajero'))
);

CREATE TABLE empleado (
    id_empleado INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    fch_ingreso DATE NOT NULL DEFAULT CURRENT_DATE,
    salario NUMERIC(12,2) NOT NULL CHECK (salario >= 0),
    id_cargo INTEGER NOT NULL,
    CONSTRAINT fk_empleado_cargo
        FOREIGN KEY (id_cargo) REFERENCES cargo(id_cargo)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

-- El telefono aparece como atributo multivaluado en el diagrama.
-- Por eso se almacena en una tabla separada, permitiendo varios telefonos por empleado.
CREATE TABLE empleado_telefono (
    id_empleado INTEGER NOT NULL,
    telefono VARCHAR(25) NOT NULL,
    PRIMARY KEY (id_empleado, telefono),
    CONSTRAINT fk_empleado_telefono_empleado
        FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
        ON UPDATE CASCADE ON DELETE CASCADE
);

-- Subtipos de Empleado: su PK tambien es FK a empleado.
CREATE TABLE mesero (
    id_empleado INTEGER PRIMARY KEY,
    porcentaje_propinas NUMERIC(5,2) NOT NULL DEFAULT 0,
    CONSTRAINT ck_mesero_propinas CHECK (porcentaje_propinas BETWEEN 0 AND 100),
    CONSTRAINT fk_mesero_empleado
        FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE cocinero (
    id_empleado INTEGER PRIMARY KEY,
    especialidad VARCHAR(80) NOT NULL,
    CONSTRAINT fk_cocinero_empleado
        FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE administrador (
    id_empleado INTEGER PRIMARY KEY,
    nivel_permiso SMALLINT NOT NULL,
    CONSTRAINT ck_administrador_nivel CHECK (nivel_permiso BETWEEN 1 AND 5),
    CONSTRAINT fk_administrador_empleado
        FOREIGN KEY (id_empleado) REFERENCES empleado(id_empleado)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE cliente (
    id_cliente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    telefono VARCHAR(25),
    email VARCHAR(120) UNIQUE,
    direccion VARCHAR(180),
    CONSTRAINT ck_cliente_email CHECK (email IS NULL OR POSITION('@' IN email) > 1)
);

CREATE TABLE mesa (
    id_mesa INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero INTEGER NOT NULL UNIQUE,
    capacidad INTEGER NOT NULL,
    ubicacion VARCHAR(80) NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'disponible',
    CONSTRAINT ck_mesa_capacidad CHECK (capacidad > 0),
    CONSTRAINT ck_mesa_estado CHECK (estado IN ('disponible', 'ocupada'))
);

CREATE TABLE reserva (
    id_reserva INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    id_mesa INTEGER NOT NULL,
    fecha DATE NOT NULL,
    hora TIME NOT NULL,
    hora_fin TIME NOT NULL,
    cant_personas INTEGER NOT NULL,
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    CONSTRAINT ck_reserva_personas CHECK (cant_personas > 0),
    CONSTRAINT ck_reserva_horas CHECK (hora_fin > hora),
    CONSTRAINT ck_reserva_estado
        CHECK (estado IN ('Pendiente', 'Confirmada', 'Cancelada', 'Asistio', 'No asistio')),
    CONSTRAINT fk_reserva_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_reserva_mesa
        FOREIGN KEY (id_mesa) REFERENCES mesa(id_mesa)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE categoria (
    id_categoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(60) NOT NULL UNIQUE
);

CREATE TABLE producto (
    id_producto INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL,
    precio NUMERIC(10,2) NOT NULL,
    tiempo_preparacion INTEGER NOT NULL DEFAULT 10,
    disponible BOOLEAN NOT NULL DEFAULT TRUE,
    id_categoria INTEGER NOT NULL,
    CONSTRAINT ck_producto_precio CHECK (precio >= 0),
    CONSTRAINT ck_producto_tiempo CHECK (tiempo_preparacion > 0),
    CONSTRAINT fk_producto_categoria
        FOREIGN KEY (id_categoria) REFERENCES categoria(id_categoria)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE ingrediente (
    id_ingrediente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100) NOT NULL UNIQUE,
    unidad_medida VARCHAR(25) NOT NULL
);

CREATE TABLE producto_ingrediente (
    id_producto INTEGER NOT NULL,
    id_ingrediente INTEGER NOT NULL,
    cantidad_necesaria NUMERIC(10,3) NOT NULL,
    PRIMARY KEY (id_producto, id_ingrediente),
    CONSTRAINT ck_producto_ingrediente_cantidad CHECK (cantidad_necesaria > 0),
    CONSTRAINT fk_pi_producto
        FOREIGN KEY (id_producto) REFERENCES producto(id_producto)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pi_ingrediente
        FOREIGN KEY (id_ingrediente) REFERENCES ingrediente(id_ingrediente)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE pedido (
    id_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente INTEGER NOT NULL,
    id_mesa INTEGER,
    id_empleado_registra INTEGER NOT NULL,
    cant_personas INTEGER NOT NULL DEFAULT 1,
    fecha_hora TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    estado VARCHAR(20) NOT NULL DEFAULT 'Pendiente',
    CONSTRAINT ck_pedido_estado
        CHECK (estado IN ('Pendiente', 'Preparacion', 'Listo', 'Entregado', 'Cancelado')),
    CONSTRAINT ck_pedido_personas CHECK (cant_personas > 0),
    CONSTRAINT fk_pedido_cliente
        FOREIGN KEY (id_cliente) REFERENCES cliente(id_cliente)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_mesa
        FOREIGN KEY (id_mesa) REFERENCES mesa(id_mesa)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_pedido_empleado
        FOREIGN KEY (id_empleado_registra) REFERENCES empleado(id_empleado)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE item_pedido (
    id_pedido INTEGER NOT NULL,
    numero_linea INTEGER NOT NULL,
    id_producto INTEGER NOT NULL,
    cantidad INTEGER NOT NULL,
    precio_unitario NUMERIC(10,2) NOT NULL,
    PRIMARY KEY (id_pedido, numero_linea),
    CONSTRAINT ck_item_numero_linea CHECK (numero_linea > 0),
    CONSTRAINT ck_item_cantidad CHECK (cantidad > 0),
    CONSTRAINT ck_item_precio CHECK (precio_unitario >= 0),
    CONSTRAINT fk_item_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido)
        ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_item_producto
        FOREIGN KEY (id_producto) REFERENCES producto(id_producto)
        ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE atencion (
    id_atencion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_empleado INTEGER NOT NULL,
    id_pedido INTEGER NOT NULL,
    fch_hora_de_atencion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_atencion_mesero
        FOREIGN KEY (id_empleado) REFERENCES mesero(id_empleado)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_atencion_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido)
        ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE TABLE prepara (
    id_empleado INTEGER NOT NULL,
    id_pedido INTEGER NOT NULL,
    cantidad_platos INTEGER NOT NULL,
    PRIMARY KEY (id_empleado, id_pedido),
    CONSTRAINT ck_prepara_cantidad CHECK (cantidad_platos > 0),
    CONSTRAINT fk_prepara_cocinero
        FOREIGN KEY (id_empleado) REFERENCES cocinero(id_empleado)
        ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_prepara_pedido
        FOREIGN KEY (id_pedido) REFERENCES pedido(id_pedido)
        ON UPDATE CASCADE ON DELETE CASCADE
);

COMMIT;